int CSHARC::Run(int cycles)
{
	if (cycles <= 0)
		return 0;
	if (m_halted || m_fatal)
	{
		// A halted MAME CPU just lets the time pass; the scheduler's timers still run
		if (!m_fatal)
		{
			try
			{
				advance_iop_timer(cycles);
			}
			catch (const SHARCFatalError &e)
			{
				ErrorLog("SHARC: %s", e.what());
				m_fatal = true;
			}
		}
		return cycles;
	}

	m_core->icount = cycles;
	m_cyclesRequested = cycles;
	m_inRun = true;
	try
	{
		execute_run();
	}
	catch (const SHARCFatalError &e)
	{
		ErrorLog("SHARC: %s", e.what());
		m_fatal = true;
		m_stall_allowed = false;
		m_core->icount = 0;
	}
	m_inRun = false;
	int used = m_cyclesRequested - m_core->icount;   // (EndSlice() lowers m_cyclesRequested)
	m_core->icount = 0;
	return used;
}

int CSHARC::CyclesRun() const
{
	return m_inRun ? m_cyclesRequested - m_core->icount : 0;
}

void CSHARC::Stall()
{
	if (m_inRun)
		m_stalled = true;
}

// The run loop counts the current instruction off after it completes: one
// cycle is left for it, and the cycles given up aren't charged
void CSHARC::EndSlice()
{
	if (m_inRun && m_core->icount > 1)
	{
		m_cyclesRequested -= m_core->icount - 1;
		m_core->icount = 1;
	}
}


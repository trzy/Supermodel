/* | 00010100x | */

/* system register bit manipulation */
void CSHARC::sharcop_sysreg_bitop()
{
	int const bop = (m_core->opcode >> 37) & 0x7;
	int const sreg = (m_core->opcode >> 32) & 0xf;
	uint32_t const data = uint32_t(m_core->opcode);

	uint32_t src = GET_UREG(0x70 | sreg);

	switch (bop)
	{
		case 0:     /* SET */
		{
			src |= data;
			break;
		}
		case 1:     /* CLEAR */
		{
			src &= ~data;
			break;
		}
		case 2:     /* TOGGLE */
		{
			src ^= data;
			break;
		}
		case 4:     /* TEST */
		{
			if ((src & data) == data)
				m_core->astat |= BTF;
			else
				m_core->astat &= ~BTF;
			break;
		}
		case 5:     /* XOR */
		{
			if (src == data)
				m_core->astat |= BTF;
			else
				m_core->astat &= ~BTF;
			break;
		}
		default:
			throw emu_fatalerror("%s: sysreg_bitop: invalid bitop %d", tag(), bop);
	}

	SET_UREG(0x70 | sreg, src);
}


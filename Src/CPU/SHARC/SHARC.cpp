/* Fm = Fxm * Fym,   Fa = FLOAT Rxa BY Rya */
void CSHARC::compute_fmul_float_scaled(int fm, int fxm, int fym, int fa, int rxa, int rya)
{
	CLEAR_MULTIPLIER_FLAGS();
	CLEAR_ALU_FLAGS();

	SHARC_REG r_mul = FMUL(fxm, fym);

	SHARC_REG x;
	SHARC_REG r_alu;

	x.f = float(int32_t(REG(rxa)));

	r_alu.r = SCALB(x, rya);

	m_core->astat |= (r_alu.f < 0.0f) ? AN : 0;
	// AZ
	m_core->astat |= IS_FLOAT_DENORMAL_OR_ZERO(r_alu.r) ? AZ : 0;
	// AU
	m_core->stky |= IS_FLOAT_DENORMAL(r_alu.r) ? AUS : 0;
	/* TODO: set AV if overflowed */

	FREG(fm) = r_mul.f;
	FREG(fa) = r_alu.f;
	m_core->astat |= AF;
}

/* Fm = Fxm * Fym,   Ra = FIX Fxa BY Rya */
void CSHARC::compute_fmul_fix_scaled(int fm, int fxm, int fym, int ra, int fxa, int rya)
{
	CLEAR_MULTIPLIER_FLAGS();
	CLEAR_ALU_FLAGS();

	SHARC_REG r_mul = FMUL(fxm, fym);

	int32_t alu_i;
	bool fix_overflow;
	SHARC_REG r_alu;

	r_alu.r = SCALB(m_core->r[fxa], rya);

	if (m_core->mode1 & MODE1_TRUNCATE)
	{
		alu_i = FixValue(floorf(r_alu.f), fix_overflow);   // Supermodel (review fix): towards -infinity, as FIX
	}
	else
	{
		alu_i = FixValue(nearbyintf(r_alu.f), fix_overflow); // assume rounding mode is set to FE_TONEAREST
	}

	SET_FLAG_AN(alu_i);
	// AZ
	SET_FLAG_AZ(alu_i);
	// AU
	m_core->stky |= (IS_FLOAT_DENORMAL(r_alu.r)) ? AUS : 0;
	// AI
	m_core->astat |= (IS_FLOAT_NAN(REG(fxa))) ? AI : 0;
	if (fix_overflow)
	{
		m_core->astat |= AV;
		m_core->stky |= AVS;
	}

	FREG(fm) = r_mul.f;
	REG(ra) = alu_i;
	m_core->astat |= AF;
}


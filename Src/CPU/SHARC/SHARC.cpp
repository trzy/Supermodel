// MODE1 TRUNC selects round-to-zero for all ALU operations and floating point
// multiplies (ADSP-2106x manual, "Rounding Mode"); MAME rounded to nearest. The
// result is formed in double (exact for a product; a sum carries its rounding
// error) and stepped towards zero if the float rounded away from zero.
float CSHARC::RoundToZero(double value, double error) const
{
	float f = float(value);
	if (f == 0.0f || !std::isfinite(f))
		return f;
	double rem = (value - double(f)) + error;   // exact result - f
	if ((f > 0.0f && rem < 0.0) || (f < 0.0f && rem > 0.0))
		f = std::nextafter(f, 0.0f);
	return f;
}

// Supermodel: a double in the normal float range truncated towards zero to a
// float, exactly: its low 29 mantissa bits cleared. False out of that range.
static inline bool TruncateToFloat(uint64_t bits, float &out)
{
	int const exponent = int((bits >> 52) & 0x7ff) - 1023;
	if (exponent < -126 || exponent > 126)
		return false;
	bits &= ~((uint64_t(1) << 29) - 1);
	double d;
	memcpy(&d, &bits, sizeof(d));
	out = float(d);
	return true;
}

float CSHARC::AddF(float a, float b) const
{
	if (!(m_core->mode1 & MODE1_TRUNCATE))
		return a + b;
	double s = double(a) + double(b);
	double bb = s - double(a);
	double err = (double(a) - (s - bb)) + (double(b) - bb);
	// fast path: the exact sum s + err truncates as s does, unless s is
	// exactly a float and err points towards zero
	uint64_t bits;
	memcpy(&bits, &s, sizeof(bits));
	float r;
	if (((bits & ((uint64_t(1) << 29) - 1)) != 0 || err == 0.0 || ((err > 0.0) == (s > 0.0))) && TruncateToFloat(bits, r))
		return r;
	return RoundToZero(s, err);
}

float CSHARC::MulF(float a, float b) const
{
	if (!(m_core->mode1 & MODE1_TRUNCATE))
		return a * b;
	double const p = double(a) * double(b);   // exact
	uint64_t bits;
	memcpy(&bits, &p, sizeof(bits));
	float r;
	if (TruncateToFloat(bits, r))
		return r;
	return RoundToZero(p, 0.0);
}

// FIX: out of range or infinite gives all 1s, or with ALUSAT the largest
// positive/negative integer, and sets AV; NaN gives all 1s (manual, FIX)
int32_t CSHARC::FixValue(float value, bool &overflow) const
{
	overflow = false;
	if (std::isnan(value))
		return -1;
	if (value >= 2147483648.0f || value < -2147483648.0f)
	{
		overflow = true;
		if (m_core->mode1 & MODE1_ALUSAT)
			return value > 0.0f ? 0x7fffffff : int32_t(0x80000000);
		return -1;
	}
	return int32_t(value);
}



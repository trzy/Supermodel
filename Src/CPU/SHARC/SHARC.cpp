void CSHARC::build_opcode_table()
{
	for (int i = 0; i < int(std::size(m_sharc_op)); i++)
	{
		m_sharc_op[i] = &CSHARC::sharcop_unimplemented;

		const uint16_t op = i << 7;

		size_t j = 0;
		while (j < s_num_ops)
		{
			auto &opcode = s_sharc_opcode_table[j++];
			if ((opcode.op_mask & op) == opcode.op_bits)
			{
				m_sharc_op[i] = opcode.handler;
				break;
			}
		}
		while (j < s_num_ops)
		{
			auto &opcode = s_sharc_opcode_table[j++];
			if ((opcode.op_mask & op) == opcode.op_bits)
			{
				throw emu_fatalerror("build_opcode_table: table already filled! (i=%04X, j=%d)\n", i, int(j));
			}
		}
	}
}


UINT32 CSHARC::GetReg(unsigned n) const
{
	if (n >= REG_R0 && n < REG_R0 + 16)
		return uint32_t(m_core->r[n - REG_R0].r);
	if (n >= REG_I0 && n < REG_B0 + 16)
	{
		unsigned const k = (n - REG_I0) & 15;
		const sharc_internal_state::SHARC_DAG &dag = (k < 8) ? m_core->dag1 : m_core->dag2;
		switch ((n - REG_I0) >> 4)
		{
		case 0:  return dag.i[k & 7];
		case 1:  return dag.m[k & 7];
		case 2:  return dag.l[k & 7];
		default: return dag.b[k & 7];
		}
	}
	switch (n)
	{
	case REG_PC:       return m_core->pc;
	case REG_PCSTK:    return m_core->pcstk;
	case REG_PCSTKP:   return m_core->pcstkp;
	case REG_LSTKP:    return m_core->lstkp;
	case REG_FADDR:    return m_core->faddr;
	case REG_DADDR:    return m_core->daddr;
	case REG_MODE1:    return m_core->mode1;
	case REG_MODE2:    return m_core->mode2;
	case REG_ASTAT:    return m_core->astat;
	case REG_STKY:     return m_core->stky;
	case REG_IRPTL:    return m_core->irptl;
	case REG_IMASK:    return m_core->imask;
	case REG_IMASKP:   return m_core->imaskp;
	case REG_USTAT1:   return m_core->ustat1;
	case REG_USTAT2:   return m_core->ustat2;
	case REG_LCNTR:    return m_core->lcntr;
	case REG_CURLCNTR: return m_core->curlcntr;
	case REG_STSTKP:   return uint32_t(m_core->status_stkp);
	case REG_PX_LO:    return uint32_t(m_core->px);
	case REG_PX_HI:    return uint32_t(m_core->px >> 32);
	case REG_MRF_LO:   return uint32_t(m_core->mrf);
	case REG_MRF_HI:   return uint32_t(m_core->mrf >> 32);
	case REG_MRB_LO:   return uint32_t(m_core->mrb);
	case REG_MRB_HI:   return uint32_t(m_core->mrb >> 32);
	default:           return 0;
	}
}

void CSHARC::SetReg(unsigned n, UINT32 v)
{
	if (n >= REG_R0 && n < REG_R0 + 16)
	{
		m_core->r[n - REG_R0].r = int32_t(v);
		return;
	}
	if (n >= REG_I0 && n < REG_B0 + 16)
	{
		unsigned const k = (n - REG_I0) & 15;
		sharc_internal_state::SHARC_DAG &dag = (k < 8) ? m_core->dag1 : m_core->dag2;
		if (k >= 8)
			v &= 0x00ffffff;   // MAME's state masks for the DAG2 registers
		switch ((n - REG_I0) >> 4)
		{
		case 0:  dag.i[k & 7] = v; break;
		case 1:  dag.m[k & 7] = v; break;
		case 2:  dag.l[k & 7] = v; break;
		default: dag.b[k & 7] = v; break;
		}
		return;
	}
	switch (n)
	{
	case REG_PC:       CHANGE_PC(v & 0x00ffffff); m_retry = false; break;   // next instruction at v
	case REG_PCSTK:    m_core->pcstk = v & 0x00ffffff; break;
	case REG_PCSTKP:   m_core->pcstkp = v & 0x1f; break;
	case REG_LSTKP:    m_core->lstkp = v & 0x07; break;
	case REG_FADDR:    m_core->faddr = v; break;
	case REG_DADDR:    m_core->daddr = v; break;
	case REG_MODE1:    m_core->mode1 = v; break;
	case REG_MODE2:    m_core->mode2 = v; break;
	case REG_ASTAT:    m_core->astat = v; break;
	case REG_STKY:     m_core->stky = v; break;
	case REG_IRPTL:    m_core->irptl = v; break;
	case REG_IMASK:    m_core->imask = v; break;
	case REG_IMASKP:   m_core->imaskp = v; break;
	case REG_USTAT1:   m_core->ustat1 = v; break;
	case REG_USTAT2:   m_core->ustat2 = v; break;
	case REG_LCNTR:    m_core->lcntr = v; break;
	case REG_CURLCNTR: m_core->curlcntr = v; break;
	case REG_STSTKP:   m_core->status_stkp = int32_t(v); break;
	case REG_PX_LO:    m_core->px = (m_core->px & 0xffffffff00000000ULL) | v; break;
	case REG_PX_HI:    m_core->px = (m_core->px & 0xffffffffULL) | (uint64_t(v) << 32); break;
	case REG_MRF_LO:   m_core->mrf = (m_core->mrf & 0xffffffff00000000ULL) | v; break;
	case REG_MRF_HI:   m_core->mrf = (m_core->mrf & 0xffffffffULL) | (uint64_t(v) << 32); break;
	case REG_MRB_LO:   m_core->mrb = (m_core->mrb & 0xffffffff00000000ULL) | v; break;
	case REG_MRB_HI:   m_core->mrb = (m_core->mrb & 0xffffffffULL) | (uint64_t(v) << 32); break;
	default:           break;
	}
}

void CSHARC::SaveState(CBlockFile *StateFile, const char *name)
{
	StateFile->NewBlock(name, __FILE__);

	for (const SHARC_REG &r : m_core->r)       StateFile->Write(r.r);
	for (const SHARC_REG &r : m_core->reg_alt) StateFile->Write(r.r);
	StateFile->Write(m_core->pc);
	StateFile->Write(m_core->mrf);
	StateFile->Write(m_core->mrb);

	StateFile->Write(m_core->pcstack);
	StateFile->Write(m_core->lcstack);
	StateFile->Write(m_core->lastack);
	StateFile->Write(m_core->lstkp);

	StateFile->Write(m_core->faddr);
	StateFile->Write(m_core->daddr);
	StateFile->Write(m_core->pcstk);
	StateFile->Write(m_core->pcstkp);
	StateFile->Write(m_core->laddr.pack());
	StateFile->Write(m_core->curlcntr);
	StateFile->Write(m_core->lcntr);
	StateFile->Write(m_core->extdma_shift);
	StateFile->Write(m_core->iop_write_num);
	StateFile->Write(m_core->iop_data);

	const sharc_internal_state::SHARC_DAG *dags[4] = { &m_core->dag1, &m_core->dag2, &m_core->dag1_alt, &m_core->dag2_alt };
	for (const sharc_internal_state::SHARC_DAG *dag : dags)
	{
		StateFile->Write(dag->i);
		StateFile->Write(dag->m);
		StateFile->Write(dag->b);
		StateFile->Write(dag->l);
	}

	for (const SHARC_DMA_REGS &d : m_core->dma)
	{
		StateFile->Write(d.control);
		StateFile->Write(d.int_index);
		StateFile->Write(d.int_modifier);
		StateFile->Write(d.int_count);
		StateFile->Write(d.chain_ptr);
		StateFile->Write(d.gen_purpose);
		StateFile->Write(d.ext_index);
		StateFile->Write(d.ext_modifier);
		StateFile->Write(d.ext_count);
	}

	StateFile->Write(m_core->mode1);
	StateFile->Write(m_core->mode2);
	StateFile->Write(m_core->astat);
	StateFile->Write(m_core->stky);
	StateFile->Write(m_core->irptl);
	StateFile->Write(m_core->imask);
	StateFile->Write(m_core->imaskp);
	StateFile->Write(m_core->ustat1);
	StateFile->Write(m_core->ustat2);
	StateFile->Write(m_core->flag);
	StateFile->Write(m_core->syscon);
	StateFile->Write(m_msgr);
	StateFile->Write(m_core->sysstat);

	for (const auto &s : m_core->status_stack)
	{
		StateFile->Write(s.mode1);
		StateFile->Write(s.astat);
	}
	StateFile->Write(m_core->status_stkp);

	StateFile->Write(m_core->px);
	StateFile->Write(m_core->opcode);
	StateFile->Write(m_core->nfaddr);
	StateFile->Write(m_core->idle);
	StateFile->Write(m_core->irq_pending);
	StateFile->Write(m_core->active_irq_num);

	for (const SHARC_DMA_OP &d : m_core->dma_op)
	{
		StateFile->Write(d.src);
		StateFile->Write(d.dst);
		StateFile->Write(d.chain_ptr);
		StateFile->Write(d.src_modifier);
		StateFile->Write(d.dst_modifier);
		StateFile->Write(d.src_count);
		StateFile->Write(d.dst_count);
		StateFile->Write(d.pmode);
		StateFile->Write(d.chained_direction);
		StateFile->Write(d.active);
		StateFile->Write(d.chained);
	}
	StateFile->Write(m_core->dma_status);
	StateFile->Write(m_core->write_stalled);
	StateFile->Write(m_core->interrupt_active);
	StateFile->Write(m_core->iop_delayed_reg);
	StateFile->Write(m_core->iop_delayed_data);
	StateFile->Write(m_core->delay_slot1);
	StateFile->Write(m_core->delay_slot2);
	StateFile->Write(m_core->systemreg_latency_cycles);
	StateFile->Write(m_core->systemreg_latency_reg);
	StateFile->Write(m_core->systemreg_latency_data);
	StateFile->Write(m_core->systemreg_previous_data);
	StateFile->Write(m_core->astat_old);
	StateFile->Write(m_core->astat_old_old);
	StateFile->Write(m_core->astat_old_old_old);

	StateFile->Write(m_blocks);
	StateFile->Write(m_dm_short_se);
	StateFile->Write(m_iop_delay_cycles);
	StateFile->Write(m_halted);
	StateFile->Write(m_retry);
}


void CSHARC::CHANGE_PC(uint32_t newpc)
{
	m_core->pc = newpc;
	m_core->daddr = newpc;
	m_core->faddr = newpc+1;
	m_core->nfaddr = newpc+2;
}

void CSHARC::CHANGE_PC_DELAYED(uint32_t newpc)
{
	m_core->nfaddr = newpc;

	m_core->delay_slot1 = m_core->pc;
	m_core->delay_slot2 = m_core->daddr;
}

// Supermodel: MAME's delayed_iop_timer callback, called when m_iop_delay_cycles runs out
void CSHARC::sharc_iop_delayed_write_callback()
{
	switch (m_core->iop_delayed_reg)
	{
		case 0x1c:
		{
			if (m_core->iop_delayed_data & 0x1)
			{
				sharc_dma_exec(6);
			}
			break;
		}

		case 0x1d:
		{
			if (m_core->iop_delayed_data & 0x1)
			{
				sharc_dma_exec(7);
			}
			break;
		}

		default:
			throw emu_fatalerror("SHARC: sharc_iop_delayed_write: unknown IOP register %02X\n", m_core->iop_delayed_reg);
	}

	m_iop_delay_cycles = 0;   // delayed_iop_timer->adjust(attotime::never)
}

// Supermodel: the timer counts this core's cycles (instructions, idle and halted cycles)
void CSHARC::sharc_iop_delayed_w(uint32_t reg, uint32_t data, int cycles)
{
	m_core->iop_delayed_reg = reg;
	m_core->iop_delayed_data = data;

	m_iop_delay_cycles = cycles;
}

void CSHARC::advance_iop_timer(int cycles)
{
	if (m_iop_delay_cycles > 0)
	{
		m_iop_delay_cycles -= cycles;
		if (m_iop_delay_cycles <= 0)
		{
			m_iop_delay_cycles = 0;
			sharc_iop_delayed_write_callback();
		}
	}
}

// 0 012 0h 0l 1h
// 1 453 2h 2l 1l
// 2 678 3h 3l 4h
// 3 ab9 5h 5l 4l
// 4 cde 6h 6l 7h

uint64_t CSHARC::pm_r(unsigned n, uint32_t offset) const
{
	uint32_t slot = offset >> 12;
	uint32_t base = (offset & 0xfff) + (slot >> 1) * (3<<12);
	if (slot & 1)
		return (uint64_t(m_blocks[n][base + 0x2000]) << 16) | (m_blocks[n][base + 0x1000] & 0xffff);
	else
		return (uint64_t(m_blocks[n][base         ]) << 16) | (m_blocks[n][base + 0x1000] >> 16);
}

void CSHARC::pm_w(unsigned n, uint32_t offset, uint64_t data, uint64_t mem_mask)
{
	uint32_t slot = offset >> 12;
	uint32_t base = (offset & 0xfff) + (slot >> 1) * (3<<12);
	bool const accessing_bits_0_15 = (mem_mask & 0xffff) != 0;
	if (slot & 1)
	{
		if (accessing_bits_0_15)
			m_blocks[n][base + 0x1000] = (m_blocks[n][base + 0x1000] & 0xffff0000) | (data & 0xffff);
		m_blocks[n][base + 0x2000] = uint32_t((m_blocks[n][base + 0x2000] & ~(mem_mask >> 16)) | ((data & mem_mask) >> 16));
	}
	else
	{
		m_blocks[n][base + 0x0000] = uint32_t((m_blocks[n][base + 0x0000] & ~(mem_mask >> 16)) | ((data & mem_mask) >> 16));
		if (accessing_bits_0_15)
			m_blocks[n][base + 0x1000] = uint32_t((m_blocks[n][base + 0x1000] & 0xffff) | ((data & 0xffff) << 16));
	}
}

// Supermodel: MAME reads the blocks as little endian 16-bit arrays
uint32_t CSHARC::dm_short_r(unsigned n, uint32_t offset) const
{
	return (m_blocks[n][(offset >> 1) & 0x7fff] >> ((offset & 1) * 16)) & 0xffff;
}

uint32_t CSHARC::dm_short_se_r(unsigned n, uint32_t offset) const
{
	return uint32_t(int32_t(int16_t(uint16_t(dm_short_r(n, offset)))));
}

void CSHARC::dm_short_w(unsigned n, uint32_t offset, uint32_t data)
{
	uint32_t &w = m_blocks[n][(offset >> 1) & 0x7fff];
	unsigned const shift = (offset & 1) * 16;
	w = (w & ~(0xffffu << shift)) | ((data & 0xffff) << shift);
}

/* IOP registers */
uint32_t CSHARC::iop_r(uint32_t offset, bool side_effects)
{
	switch (offset)
	{
		case 0x00: return 0;    // System configuration

		case 0x37:      // DMA status
		{
			return m_core->dma_status;
		}

		case 0x08: case 0x09: case 0x0a: case 0x0b: case 0x0c: case 0x0d: case 0x0e: case 0x0f:
			return m_msgr[offset - 0x08];   // Supermodel: message registers
		default:
		if (side_effects)
			throw emu_fatalerror("sharc_iop_r: Unimplemented IOP reg %02X at %08X\n", offset, m_core->pc);

		return 0;
	}
}

void CSHARC::iop_w(uint32_t offset, uint32_t data)
{
	switch (offset)
	{
		case 0x00: m_core->syscon = data; break;
		case 0x02: break;       // External Memory Wait State Configuration
		case 0x04: // External port DMA buffer 0
		{
			external_dma_write(m_core->extdma_shift, data);
			m_core->extdma_shift++;
			if (m_core->extdma_shift == 3)
				m_core->extdma_shift = 0;
			break;
		}

		case 0x08: case 0x09: case 0x0a: case 0x0b: case 0x0c: case 0x0d: case 0x0e: case 0x0f:
			m_msgr[offset - 0x08] = data;   // Supermodel: message registers 0-7
			break;

		case 0x14: // reserved??? written by Last Bronx
		case 0x17: break;

		// DMA 6
		case 0x1c:
		{
			m_core->dma[6].control = data;
			if (data & 0x1)
			{
				sharc_iop_delayed_w(0x1c, data, 1);
			}
			break;
		}

		case 0x20: break;

		case 0x40: m_core->dma[6].int_index = data; return;
		case 0x41: m_core->dma[6].int_modifier = data; return;
		case 0x42: m_core->dma[6].int_count = data; return;
		case 0x43: m_core->dma[6].chain_ptr = data; return;
		case 0x44: m_core->dma[6].gen_purpose = data; return;
		case 0x45: m_core->dma[6].ext_index = data; return;
		case 0x46: m_core->dma[6].ext_modifier = data; return;
		case 0x47: m_core->dma[6].ext_count = data; return;

		// DMA 7
		case 0x1d:
		{
			m_core->dma[7].control = data;
			if (data & 0x1)
			{
				sharc_iop_delayed_w(0x1d, data, 30);
			}
			break;
		}

		case 0x48: m_core->dma[7].int_index = data; return;
		case 0x49: m_core->dma[7].int_modifier = data; return;
		case 0x4a: m_core->dma[7].int_count = data; return;
		case 0x4b: m_core->dma[7].chain_ptr = data; return;
		case 0x4c: m_core->dma[7].gen_purpose = data; return;
		case 0x4d: m_core->dma[7].ext_index = data; return;
		case 0x4e: m_core->dma[7].ext_modifier = data; return;
		case 0x4f: m_core->dma[7].ext_count = data; return;

		default:
			throw emu_fatalerror("sharc_iop_w: Unimplemented IOP reg %02X, %08X at %08X\n", offset, data, m_core->pc);
	}
}


/******************************************************************************
 Supermodel: the internal address maps (MAME's pgm_2m / data_2m) and the bus
******************************************************************************/

// data_2m: IOP registers at 0x00000-0x000ff, block 0 at 0x20000-0x27fff, block 1
// at 0x28000-0x3ffff (mirrored), short words (16-bit, sign extended when MODE1
// SSE has taken effect) at 0x40000-0x4ffff (block 0) and 0x50000-0x7ffff
// (block 1, mirrored). The rest of 0x00000-0x7ffff is unmapped.
uint32_t CSHARC::dm_internal_r(uint32_t address, bool side_effects)
{
	if (address < 0x100)
		return iop_r(address, side_effects);
	if (address >= 0x20000 && address < 0x40000)
		return m_blocks[(address & 0x18000) ? 1 : 0][address & 0x7fff];
	if (address >= 0x40000 && address < 0x80000)
	{
		unsigned const n = (address & 0x30000) ? 1 : 0;
		return m_dm_short_se ? dm_short_se_r(n, address & 0xffff) : dm_short_r(n, address & 0xffff);
	}
	return 0;
}

void CSHARC::dm_internal_w(uint32_t address, uint32_t data)
{
	if (address < 0x100)
		iop_w(address, data);
	else if (address >= 0x20000 && address < 0x40000)
		m_blocks[(address & 0x18000) ? 1 : 0][address & 0x7fff] = data;
	else if (address >= 0x40000 && address < 0x80000)
		dm_short_w((address & 0x30000) ? 1 : 0, address & 0xffff, data);
}

// pgm_2m: block 0 at 0x20000-0x24fff, block 1 at 0x28000-0x2cfff (mirrored
// at 0x30000 and 0x38000)
bool CSHARC::pm_internal(uint32_t address, unsigned &block, uint32_t &offset) const
{
	if ((address & ~0x1ffffu) != 0x20000)
		return false;
	block = (address & 0x18000) ? 1 : 0;
	offset = address & 0x7fff;
	return true;
}

uint64_t CSHARC::program_read_qword(uint32_t address)
{
	unsigned block;
	uint32_t offset;
	if (pm_internal(address, block, offset))
		return (offset < 0x5000) ? pm_r(block, offset) : 0;
	uint64_t const data = m_bus->ReadProgram(address);
	stall_check();
	return data;
}

// Supermodel: an external write gets the data without the mask
void CSHARC::program_write_qword(uint32_t address, uint64_t data, uint64_t mem_mask)
{
	unsigned block;
	uint32_t offset;
	if (pm_internal(address, block, offset))
	{
		if (offset < 0x5000)
			pm_w(block, offset, data, mem_mask);
		return;
	}
	m_bus->WriteProgram(address, data & mem_mask);
	stall_check();
}

// SHARC memory operations (sharcinternal.ipp)

// When PM bus is used to transfer 32-bit data, it is aligned to the upper 32 bits of the bus
uint32_t CSHARC::pm_read32(uint32_t address)
{
	return uint32_t(program_read_qword(address) >> 16);
}

void CSHARC::pm_write32(uint32_t address, uint32_t data)
{
	// TODO: mask should probably be set to all ones
	program_write_qword(address, uint64_t(data) << 16, 0x0000ffffffff0000U);
}

uint64_t CSHARC::pm_read48(uint32_t address)
{
	return program_read_qword(address);
}

void CSHARC::pm_write48(uint32_t address, uint64_t data)
{
	program_write_qword(address, data);
}

uint32_t CSHARC::dm_read32(uint32_t address)
{
	if (address < 0x80000)
		return dm_internal_r(address);
	uint32_t const data = m_bus->ReadData(address);
	stall_check();
	return data;
}

void CSHARC::dm_write32(uint32_t address, uint32_t data)
{
	if (address < 0x80000)
	{
		dm_internal_w(address, data);
		return;
	}
	m_bus->WriteData(address, data);
	stall_check();
}


/******************************************************************************
 Supermodel: stalls

 MAME's Model 2B never stalls the SHARC (it polls the FIFO flags), but a bus
 may. An instruction stalled by the bus is undone and executed again on the
 next Run() without being fetched again (the loop and pipeline updates done
 before it ran are kept). Instructions that change registers before their
 memory access take a checkpoint of what they can change (stall_checkpoint_dm
 /pm, only for external addresses); the others access memory first.
******************************************************************************/

void CSHARC::stall_checkpoint()
{
	std::copy(std::begin(m_core->r), std::end(m_core->r), std::begin(m_ckpt.r));
	m_ckpt.mrf = m_core->mrf;
	m_ckpt.mrb = m_core->mrb;
	m_ckpt.px = m_core->px;
	m_ckpt.astat = m_core->astat;
	m_ckpt.stky = m_core->stky;
	std::copy(std::begin(m_core->dag1.i), std::end(m_core->dag1.i), std::begin(m_ckpt.dag1_i));
	std::copy(std::begin(m_core->dag2.i), std::end(m_core->dag2.i), std::begin(m_ckpt.dag2_i));
	m_ckpt_valid = true;
}

void CSHARC::stall_restore()
{
	if (!m_ckpt_valid)
		return;
	std::copy(std::begin(m_ckpt.r), std::end(m_ckpt.r), std::begin(m_core->r));
	m_core->mrf = m_ckpt.mrf;
	m_core->mrb = m_ckpt.mrb;
	m_core->px = m_ckpt.px;
	m_core->astat = m_ckpt.astat;
	m_core->stky = m_ckpt.stky;
	std::copy(std::begin(m_ckpt.dag1_i), std::end(m_ckpt.dag1_i), std::begin(m_core->dag1.i));
	std::copy(std::begin(m_ckpt.dag2_i), std::end(m_ckpt.dag2_i), std::begin(m_core->dag2.i));
	m_ckpt_valid = false;
}

// After a bus access
void CSHARC::stall_check()
{
	if (m_stalled)
	{
		m_stalled = false;
		if (m_stall_allowed)
			throw SHARCStall();
		DebugLog("SHARC: bus stall outside an instruction ignored at %08X\n", m_core->pc);
	}
}



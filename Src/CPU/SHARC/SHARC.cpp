UINT64 CSHARC::ReadProgramWord(UINT32 addr)
{
	unsigned block;
	uint32_t offset;
	if (pm_internal(addr, block, offset))
		return (offset < 0x5000) ? pm_r(block, offset) : 0;
	bool const stalled = m_stalled;
	UINT64 const data = m_bus->ReadProgram(addr);
	m_stalled = stalled;
	return data;
}

UINT32 CSHARC::ReadDataWord(UINT32 addr)
{
	if (addr < 0x80000)
		return dm_internal_r(addr, false);
	bool const stalled = m_stalled;
	UINT32 const data = m_bus->ReadData(addr);
	m_stalled = stalled;
	return data;
}


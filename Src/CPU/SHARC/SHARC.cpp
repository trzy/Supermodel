/* Fx + Fy,   Fx - Fy */
std::pair<CSHARC::SHARC_REG, CSHARC::SHARC_REG> CSHARC::FADD_FSUB(int fx, int fy)
{
	std::pair<SHARC_REG, SHARC_REG> r;
	bool const xemax = (REG(fx) & FLOAT_EXPONENT_MASK) == FLOAT_EXPONENT_MASK;
	bool const yemax = (REG(fy) & FLOAT_EXPONENT_MASK) == FLOAT_EXPONENT_MASK;

	if ((xemax && ((REG(fx) & FLOAT_MANTISSA_MASK) != 0)) || (yemax && (REG(fy) & FLOAT_MANTISSA_MASK) != 0))
	{
		// at least one NaN
		r.first.r = FLOAT_CANONICAL_NAN;
		r.second.r = FLOAT_CANONICAL_NAN;
		m_core->astat |= AI;
		m_core->stky |= AIS;
	}
	else if (!xemax || !yemax)
	{
		// neither NaN, at least one not infinity
		SHARC_REG x, y;
		x.r = FLOAT_FLUSH_DENORMAL(REG(fx));
		y.r = FLOAT_FLUSH_DENORMAL(REG(fy));
		r.first.f = AddF(x.f, y.f);
		r.second.f = AddF(x.f, -y.f);

		if (IS_FLOAT_INFINITY(r.first.r))
		{
			m_core->astat |= AV;
			m_core->stky |= AVS;
			if ((m_core->mode1 & MODE1_TRUNCATE) && !IS_FLOAT_INFINITY(x.r) && !IS_FLOAT_INFINITY(y.r))   // an overflow, not an infinite operand
				r.first.r = (r.first.r & FLOAT_SIGN_MASK) | 0x7f7fffff;
		}
		else if (IS_FLOAT_DENORMAL_OR_ZERO(r.first.r))
		{
			m_core->astat |= AZ;
			m_core->stky |= ((r.first.r & FLOAT_MANTISSA_MASK) != 0) ? AUS : 0;
			r.first.r &= FLOAT_SIGN_MASK;
		}

		if (IS_FLOAT_INFINITY(r.second.r))
		{
			m_core->astat |= AV;
			m_core->stky |= AVS;
			if ((m_core->mode1 & MODE1_TRUNCATE) && !IS_FLOAT_INFINITY(x.r) && !IS_FLOAT_INFINITY(y.r))   // an overflow, not an infinite operand
				r.second.r = (r.second.r & FLOAT_SIGN_MASK) | 0x7f7fffff;
		}
		else if (IS_FLOAT_DENORMAL_OR_ZERO(r.second.r))
		{
			m_core->astat |= AZ;
			m_core->stky |= ((r.second.r & FLOAT_MANTISSA_MASK) != 0) ? AUS : 0;
			r.second.r &= FLOAT_SIGN_MASK;
		}

		m_core->astat |= ((r.first.r | r.second.r) & FLOAT_SIGN_MASK) ? AN : 0;
	}
	else
	{
		// both infinity
		if ((REG(fx) ^ REG(fy)) & FLOAT_SIGN_MASK)
		{
			// opposite signs - sum is NaN
			r.first.r = FLOAT_CANONICAL_NAN;
			r.second.r =  (REG(fx) & FLOAT_SIGN_MASK) | ((m_core->mode1 & MODE1_TRUNCATE) ? 0x7f7fffff : FLOAT_INFINITY);   // Supermodel (review fix): the bits
		}
		else
		{
			// same sign - difference is NaN
			r.first.r =  (REG(fx) & FLOAT_SIGN_MASK) | ((m_core->mode1 & MODE1_TRUNCATE) ? 0x7f7fffff : FLOAT_INFINITY);   // Supermodel (review fix): the bits
			r.second.r = FLOAT_CANONICAL_NAN;
		}

		m_core->astat |= (REG(fx) & FLOAT_SIGN_MASK) ? AN : 0;
		m_core->astat |= AV | AI;
		m_core->stky |= AVS | AIS;
	}

	m_core->astat |= AF;
	return r;
}

uint32_t CSHARC::SCALB(SHARC_REG fx, int ry)
{
	uint32_t const mantissa = fx.r & FLOAT_MANTISSA_MASK;
	uint32_t const sign = fx.r & FLOAT_SIGN_MASK;

	// Supermodel (review fix): denormal inputs are flushed to zero, and zero stays zero
	if (IS_FLOAT_DENORMAL_OR_ZERO(fx.r))
	{
		m_core->astat |= AZ;
		return sign;
	}

	int64_t exponent = float_get_unbiased_exponent(fx.r);
	exponent += int32_t(REG(ry));

	if (exponent > 127)
	{
		// overflow: infinity, or NORM.MAX when rounding to zero
		m_core->astat |= AV;
		return sign | ((m_core->mode1 & MODE1_TRUNCATE) ? 0x7f7fffff : FLOAT_INFINITY);
	}
	else if (exponent < -126)
	{
		// denormal
		m_core->astat |= AZ;
		return sign;
	}
	else
	{
		return sign | float_make_biased_exponent(int(exponent)) | mantissa;
	}
}



/* Rn = Rx + Ry */
void CSHARC::compute_add(int rn, int rx, int ry)
{
	uint32_t r = REG(rx) + REG(ry);

	CLEAR_ALU_FLAGS();
	SET_FLAG_AV_ADD(r, REG(rx), REG(ry));
	SET_FLAG_AC_ADD(r, REG(rx), REG(ry));

	if ((m_core->mode1 & MODE1_ALUSAT) && (m_core->astat & AV))
		SATURATE(r);

	SET_FLAG_AN(r);
	SET_FLAG_AZ(r);

	REG(rn) = r;
	m_core->astat &= ~AF;
}


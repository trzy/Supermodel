/* Fa = Fx + Fy,   Fs = Fx - Fy */
void CSHARC::compute_dual_fadd_fsub(int fa, int fs, int fx, int fy)
{
	CLEAR_ALU_FLAGS();
	auto [r_add, r_sub] = FADD_FSUB(fx, fy);
	FREG(fa) = r_add.f;
	FREG(fs) = r_sub.f;
}



		case 0x0e:  return 0;                         /* BM */
		case 0x0f:  return (m_core->curlcntr == 1);   /* LCE */
		case 0x10:  return !(m_core->astat & AZ);     /* NOT EQUAL */
		case 0x11:  return !SHARC_COND_LT;            /* GE */
		case 0x12:  return !SHARC_COND_LE;            /* GT */

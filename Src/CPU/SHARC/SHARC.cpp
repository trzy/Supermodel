#define SET_FLAG_SV_LSHIFT(x, shift)    if((x) & ((uint32_t)0xffffffff << shift)) m_core->astat |= SV
#define SET_FLAG_SV_RSHIFT(x, shift)    if((x) & ((uint32_t)0xffffffff >> shift)) m_core->astat |= SV

#define SET_FLAG_SZ(x)                  if((x) == 0) m_core->astat |= SZ

void CSHARC::SHIFT_OPERATION_IMM(int shiftop, int data, int rn, int rx)
{
	int8_t const shift = data & 0xff;
	int const bit = data & 0x3f;
	int const len = (data >> 6) & 0x3f;

	m_core->astat &= ~(SZ|SV|SS);

	switch (shiftop)
	{
		case 0x00:      /* LSHIFT Rx BY <data8>*/
		{
			if (shift < 0)
			{
				REG(rn) = (shift > -32 ) ? (UIREG(rx) >> -shift) : 0;
			}
			else
			{
				REG(rn) = (shift < 32) ? (UIREG(rx) << shift) : 0;
				if (shift > 0)
				{
					m_core->astat |= SV;
				}
			}
			SET_FLAG_SZ(REG(rn));
			break;
		}

		case 0x01:      /* ASHIFT Rx BY <data8> */
		{
			if (shift < 0)
			{
				REG(rn) = (int32_t)REG(rx) >> ((shift > -32) ? -shift : 31);
			}
			else
			{
				REG(rn) = (shift < 32) ? ((int32_t)REG(rx) << shift) : 0;
				if (shift > 0)
				{
					m_core->astat |= SV;
				}
			}
			SET_FLAG_SZ(REG(rn));
			break;
		}

		case 0x02:      /* ROT Rx BY <data8> */
		{
			REG(rn) = rotl32(UIREG(rx), shift);
			SET_FLAG_SZ(REG(rn));
			break;
		}

		case 0x08:      /* Rn = Rn OR LSHIFT Rx BY <data8> */
		{
			uint32_t r = 0;
			if (shift < 0)
			{
				r = (shift > -32 ) ? (UIREG(rx) >> -shift) : 0;
			}
			else
			{
				r = (shift < 32) ? (UIREG(rx) << shift) : 0;
				if (shift > 0)
				{
					m_core->astat |= SV;
				}
			}

			SET_FLAG_SZ(r);

			REG(rn) = REG(rn) | r;
			break;
		}

		case 0x10:      /* FEXT Rx BY <bit6>:<len6> */
		{
			if (len == 0 || bit >= 32)
				REG(rn) = 0;
			else
				REG(rn) = BIT(REG(rx), bit, std::min(len, 32));

			SET_FLAG_SZ(REG(rn));
			if (bit+len > 32)
			{
				m_core->astat |= SV;
			}
			break;
		}

		case 0x11:      /* Rn = Rn FDEP Rx BY <bit6>:<len6> */
		{
			if (len == 0 || bit >= 32)
				REG(rn) = 0;
			else
				REG(rn) = (REG(rx) & make_bitmask<uint32_t>(std::min(len, 32))) << bit;

			SET_FLAG_SZ(REG(rn));
			if (bit+len > 32)
			{
				m_core->astat |= SV;
			}
			break;
		}

		case 0x12:      /* FEXT Rx BY <bit6>:<len6> (Sign Extended) */
		{
			if (len == 0 || bit >= 32)
				REG(rn) = 0;
			else if (bit+len > 32)
				REG(rn) = UIREG(rx) >> bit;
			else
				REG(rn) = sext(REG(rx) >> bit, std::min(len, 32));

			SET_FLAG_SZ(REG(rn));
			if (bit+len > 32)
			{
				m_core->astat |= SV;
			}
			break;
		}

		case 0x13:      /* FDEP Rx BY Ry <bit6>:<len6> (Sign Extended) */
		{
			if (len == 0 || bit >= 32)
				REG(rn) = 0;
			else
				REG(rn) = sext(REG(rx), std::min(len, 32)) << bit;

			SET_FLAG_SZ(REG(rn));
			if (bit+len > 32)
			{
				m_core->astat |= SV;
			}
			break;
		}

		case 0x19:      /* Rn = Rn OR FDEP Rx BY <bit6>:<len6> */
		{
			if (len != 0 && bit < 32)
				REG(rn) |= (REG(rx) & make_bitmask<uint32_t>(std::min(len, 32))) << bit;

			SET_FLAG_SZ(REG(rn));
			if (bit+len > 32)
			{
				m_core->astat |= SV;
			}
			break;
		}

		case 0x30:      /* BSET Rx BY <data8> */
		{
			REG(rn) = REG(rx);
			if (data >= 0 && data < 32)
			{
				REG(rn) |= (1 << data);
			}
			else
			{
				m_core->astat |= SV;
			}
			SET_FLAG_SZ(REG(rn));
			break;
		}

		case 0x31:      /* BCLR Rx BY <data8> */
		{
			REG(rn) = REG(rx);
			if (data >= 0 && data < 32)
			{
				REG(rn) &= ~(1 << data);
			}
			else
			{
				m_core->astat |= SV;
			}
			SET_FLAG_SZ(REG(rn));
			break;
		}

		case 0x32:      /* BTGL Rx BY <data8> */
		{
			REG(rn) = REG(rx);
			if (data >= 0 && data < 32)
			{
				REG(rn) ^= (1 << data);
			}
			else
			{
				m_core->astat |= SV;
			}
			SET_FLAG_SZ(REG(rn));
			break;
		}

		case 0x33:      /* BTST Rx BY <data8> */
		{
			if (data < 32)
			{
				uint32_t r = REG(rx) & (1 << data);

				SET_FLAG_SZ(r);
			}
			else
			{
				m_core->astat |= SZ | SV;
			}
			break;
		}

		default:    throw emu_fatalerror("%s: unimplemented shift operation %02X at %08X", tag(), shiftop, m_core->pc);
	}
}


/* Fn = Fx * Fy */
CSHARC::SHARC_REG CSHARC::FMUL(int fx, int fy)
{
	SHARC_REG r;
	if (IS_FLOAT_NAN_MUL(REG(fx), REG(fy)))
	{
		r.r = FLOAT_CANONICAL_NAN;
		m_core->astat |= MI;
		m_core->stky |= MIS;
	}
	else
	{
		SHARC_REG x, y;
		x.r = FLOAT_FLUSH_DENORMAL(REG(fx));
		y.r = FLOAT_FLUSH_DENORMAL(REG(fy));
		r.f = MulF(x.f, y.f);
		bool const overflow = IS_FLOAT_INFINITY(r.r);
		bool const underflow = IS_FLOAT_DENORMAL(r.r);

		m_core->astat |= (r.r & FLOAT_SIGN_MASK) ? MN : 0;
		m_core->astat |= overflow ? MV : 0;
		m_core->astat |= underflow ? MU : 0;
		m_core->stky |= overflow ? MVS : 0;
		m_core->stky |= underflow ? MUS : 0;
		// Supermodel (review fix): an underflow is a zero, a round-to-zero overflow NORM.MAX
		if (underflow)
			r.r &= FLOAT_SIGN_MASK;
		else if (overflow && (m_core->mode1 & MODE1_TRUNCATE) && !IS_FLOAT_INFINITY(x.r) && !IS_FLOAT_INFINITY(y.r))   // an overflow, not an infinite operand
			r.r = (r.r & FLOAT_SIGN_MASK) | 0x7f7fffff;
	}
	return r;
}



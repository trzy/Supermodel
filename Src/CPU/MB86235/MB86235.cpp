namespace
{
	// Used until a bus is attached: no external memory, empty FIFOs that never stall
	class CMB86235NullBus : public IMB86235Bus
	{
	public:
		UINT32 ReadData(UINT32) override { return 0; }
		void   WriteData(UINT32, UINT32) override {}
		UINT32 FIFOInPop() override { return 0; }
		bool   FIFOInEmpty() override { return true; }
		bool   FIFOInFull() override { return false; }
		void   FIFOInClear() override {}
		void   FIFOOutPush(UINT32) override {}
		bool   FIFOOutEmpty() override { return true; }
		bool   FIFOOutFull() override { return false; }
		void   FIFOOutClear() override {}
	};
	CMB86235NullBus s_null_bus;
}

CMB86235::CMB86235()
	: m_core(&m_core_state), m_bus(&s_null_bus), m_halted(false), m_fatal(false), m_inRun(false),
	  m_executing(false), m_endSlice(false), m_cyclesRequested(0)
{
	// device_start
	memset(m_core, 0, sizeof(mb86235_internal_state));
	memset(m_program, 0, sizeof(m_program));
	memset(m_dataa.mem, 0, sizeof(m_dataa.mem));
	memset(m_datab.mem, 0, sizeof(m_datab.mem));
	m_external.cpu = this;
	m_fifoin.cpu = this;
	m_fifoout.cpu = this;
}

void CMB86235::AttachBus(IMB86235Bus *bus)
{
	m_bus = bus ? bus : &s_null_bus;
}

void CMB86235::Reset()
{
	// device_reset
	m_core->pc = 0;
	m_core->delay_pc = 0;
	m_core->ppc = 0;
	m_core->delay_slot = false;

	// Supermodel: MAME keeps a pending FIFO stall across a reset (and would
	// then refetch the stalled instruction's PC)
	m_core->cur_fifo_state.has_stalled = false;
	m_core->cur_fifo_state.pc = 0;
	m_fatal = false;
}

int CMB86235::Run(int cycles)
{
	if (cycles <= 0)
		return 0;
	if (m_halted || m_fatal)
		return cycles;

	m_core->icount = cycles;
	m_cyclesRequested = cycles;
	m_inRun = true;
	m_endSlice = false;
	try
	{
		execute_run();
	}
	catch (const MB86235FatalError &e)
	{
		ErrorLog("MB86235: %s", e.what());
		m_fatal = true;
		m_core->icount = 0;
	}
	m_executing = false;
	m_inRun = false;
	m_endSlice = false;
	int used = cycles - m_core->icount;
	m_core->icount = 0;
	return used;
}

int CMB86235::CyclesRun() const
{
	return m_inRun ? m_cyclesRequested - m_core->icount : 0;
}

// MAME's stall(), plus the PC to retry (MAME records it in get_transfer_reg()
// after the FIFO pop; here it's also done for a stalling ReadData())
void CMB86235::Stall()
{
	if (!m_executing)
		return;
	m_core->cur_fifo_state.has_stalled = true;
	if ((m_core->st & RP) == 0)
		m_core->cur_fifo_state.pc = m_core->ppc;
}

bool CMB86235::IsStalled() const
{
	return m_core->cur_fifo_state.has_stalled;
}

void CMB86235::EndSlice()
{
	if (m_inRun)
		m_endSlice = true;
}

void CMB86235::SetHalt(bool halted)
{
	m_halted = halted;
	if (halted && m_inRun)
		m_endSlice = true;
}

std::string CMB86235::Disassemble(UINT32 pc, UINT64 opcode)
{
	return CMB86235Disassembler::Disassemble(pc, opcode);
}

std::string CMB86235::Disassemble(UINT32 pc) const
{
	return CMB86235Disassembler::Disassemble(pc, ReadProgram(pc));
}

UINT32 CMB86235::GetPC() const
{
	return m_core->pc;
}


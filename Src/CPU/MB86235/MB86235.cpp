void CMB86235::LoadState(CBlockFile *StateFile, const char *name)
{
	if (Result::OKAY != StateFile->FindBlock(name))
	{
		ErrorLog("Unable to load MB86235 state. Save state file is corrupt.");
		return;
	}

	StateFile->Read(m_core->pc);
	StateFile->Read(m_core->delay_pc);
	StateFile->Read(m_core->ppc);
	StateFile->Read(m_core->aa);
	StateFile->Read(m_core->ab);
	StateFile->Read(m_core->ma);
	StateFile->Read(m_core->mb);
	StateFile->Read(m_core->ar);
	StateFile->Read(m_core->sp);
	StateFile->Read(m_core->eb);
	StateFile->Read(m_core->eo);
	StateFile->Read(m_core->rpc);
	StateFile->Read(m_core->lpc);
	StateFile->Read(m_core->prp);
	StateFile->Read(m_core->pwp);
	StateFile->Read(m_core->pr);
	StateFile->Read(m_core->mod);
	StateFile->Read(m_core->st);
	StateFile->Read(m_core->pcp);
	StateFile->Read(m_core->pcs);
	StateFile->Read(m_core->pdr);
	StateFile->Read(m_core->ddr);
	StateFile->Read(m_core->delay_slot);
	StateFile->Read(m_core->cur_fifo_state.pc);
	StateFile->Read(m_core->cur_fifo_state.has_stalled);

	StateFile->Read(m_program);
	StateFile->Read(m_dataa.mem);
	StateFile->Read(m_datab.mem);

	StateFile->Read(m_halted);
	StateFile->Read(m_fatal);

	// keep the indices in range for a corrupt file (MAME's fatalerror cases)
	m_core->prp %= 24;
	m_core->pwp %= 24;
	m_core->pcp &= 3;
}

#define FSET(f) do { m_core->st |= (f); } while (false)
#define FCLR(f) do { m_core->st &= ~(f); } while (false)

void CMB86235::handle_single_step_execution()
{
	if (m_core->cur_fifo_state.has_stalled == true)
		return;

	// repeat opcode
	if (m_core->st & RP)
	{
		--m_core->rpc;
		if (m_core->rpc == 1)
			FCLR(RP);
	}
	else // normal operation
		m_core->pc++;
}

bool CMB86235::check_previous_op_stall()
{
	return (m_core->cur_fifo_state.has_stalled == true) && ((m_core->st & RP) == 0);
}

inline void CMB86235::increment_pwp()
{
	m_core->pwp++;
	if (m_core->pwp >= 24)
		m_core->pwp = 0;
}

void CMB86235::increment_prp()
{
	m_core->prp++;
	if (m_core->prp >= 24)
		m_core->prp = 0;
}

void CMB86235::decrement_prp()
{
	if (m_core->prp == 0)
		m_core->prp = 24;

	m_core->prp--;
}

void CMB86235::zero_prp()
{
	m_core->prp = 0;
}

inline uint32_t CMB86235::decode_ea(uint8_t mode, uint8_t rx, uint8_t ry, uint16_t disp, bool isbbus)
{
	uint32_t res;

	switch(mode)
	{
		case 0x00: // ARx
			return m_core->ar[rx];
		case 0x01: // ARx++
			res = m_core->ar[rx];
			if (m_core->cur_fifo_state.has_stalled == true)
				return res;
			m_core->ar[rx]++;
			m_core->ar[rx] &= 0x3fff;
			return res;
		case 0x02: // ARx--
			res = m_core->ar[rx];
			if (m_core->cur_fifo_state.has_stalled == true)
				return res;
			m_core->ar[rx]--;
			m_core->ar[rx] &= 0x3fff;
			return res;
		case 0x03: // ARx++ disp14
			res = m_core->ar[rx];
			if (m_core->cur_fifo_state.has_stalled == true)
				return res;
			m_core->ar[rx] += disp;
			m_core->ar[rx] &= 0x3fff;
			return res;
		case 0x04: // ARx + ARy
			return m_core->ar[rx] + m_core->ar[ry];
		case 0x05: // ARx + ARy++
			res = m_core->ar[ry];
			if (m_core->cur_fifo_state.has_stalled == true)
				return m_core->ar[rx] + res;
			m_core->ar[ry]++;
			m_core->ar[ry] &= 0x3fff;
			return m_core->ar[rx] + res;
		case 0x06: // ARx + ARy--
			res = m_core->ar[ry];
			if (m_core->cur_fifo_state.has_stalled == true)
				return m_core->ar[rx] + res;
			m_core->ar[ry]--;
			m_core->ar[ry] &= 0x3fff;
			return m_core->ar[rx] + res;
		case 0x07: // ARx + (ARy++ disp14)
			res = m_core->ar[ry];
			if (m_core->cur_fifo_state.has_stalled == true)
				return m_core->ar[rx] + res;
			m_core->ar[ry] += disp;
			m_core->ar[ry] &= 0x3fff;
			return m_core->ar[rx] + res;
		case 0x08: // ARx + ARyU/ARyL (A bus/B bus)
			return m_core->ar[rx] + (isbbus ? (m_core->ar[ry] & 0x7f) : (m_core->ar[ry] >> 7));
		case 0x09: // ARx + ARyL/ARyU (A bus/B bus)
			return m_core->ar[rx] + (isbbus ? (m_core->ar[ry] >> 7) : (m_core->ar[ry] & 0x7f));
		case 0x0a: // ARx + disp14
			return m_core->ar[rx] + disp;
		case 0x0b: // ARx + ARy + disp14
			return m_core->ar[rx] + m_core->ar[ry] + disp;
		case 0x0d: // ARx + [ARy++]
			res = m_core->ar[ry] & (0x1ff >> (7 - (isbbus ? ((m_core->mod >> 8) & 7) : ((m_core->mod >> 12) & 7))));
			if (m_core->cur_fifo_state.has_stalled == true)
				return m_core->ar[rx] + res;
			m_core->ar[ry]++;
			m_core->ar[ry] &= 0x3fff;
			return m_core->ar[rx] + res;
		case 0x0e: // ARx + [ARy--]
			res = m_core->ar[ry] & (0x1ff >> (7 - (isbbus ? ((m_core->mod >> 8) & 7) : ((m_core->mod >> 12) & 7))));
			if (m_core->cur_fifo_state.has_stalled == true)
				return m_core->ar[rx] + res;
			m_core->ar[ry]--;
			m_core->ar[ry] &= 0x3fff;
			return m_core->ar[rx] + res;
		case 0x0f: // ARx + [ARy++ disp14]
			res = m_core->ar[ry] & (0x1ff >> (7 - (isbbus ? ((m_core->mod >> 8) & 7) : ((m_core->mod >> 12) & 7))));
			if (m_core->cur_fifo_state.has_stalled == true)
				return m_core->ar[rx] + res;
			m_core->ar[ry] += disp;
			m_core->ar[ry] &= 0x3fff;
			return m_core->ar[rx] + res;
	}

	fatalerror("TGPx4: illegal decode_ea type %02x executed at pc=%03x\n",mode,m_core->ppc);
	return 0;
}

inline uint32_t CMB86235::read_abus(uint32_t addr)
{
	if ((addr & 0x3fff) >= 0x400)
		return m_external.read_dword((addr & 0x3fff) + (m_core->eb & 0xffc000));
	else
		return m_dataa.read_dword(addr & 0x3ff);
}

inline uint32_t CMB86235::read_bbus(uint32_t addr)
{
	return m_datab.read_dword(addr & 0x3ff);
}

inline void CMB86235::write_abus(uint32_t addr, uint32_t data)
{
	if ((addr & 0x3fff) >= 0x400)
		m_external.write_dword((addr & 0x3fff) + (m_core->eb & 0xffc000), data);
	else
		m_dataa.write_dword(addr & 0x3ff, data);
}

inline void CMB86235::write_bbus(uint32_t addr, uint32_t data)
{
	m_datab.write_dword(addr & 0x3ff, data);
}

/*********************
 *
 * Instruction fetch
 *
 ********************/

void CMB86235::execute_op(uint64_t op)
{
	switch((op >> 61) & 7)
	{
		case 0:
			do_alu2_trans2_1(op);
			break;
		case 1:
			do_alu2_trans1_1(op);
			break;
		case 4:
			do_alu1_trans2_2(op);
			break;
		case 5:
			do_alu1_trans1_2(op);
			break;
		case 2:
		case 6:
			do_alu_control(op);
			break;
		case 7:
			do_trans1_3(op);
			break;
		default:
			fatalerror("TGPx4: illegal opcode type %02x executed at pc=%03x\n",unsigned((op >> 61) & 7),m_core->ppc);
	}
}


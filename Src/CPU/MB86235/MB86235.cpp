UINT32 CMB86235::GetReg(unsigned n) const
{
	if (n >= REG_AA0 && n < REG_AA0 + 8) return m_core->aa[n - REG_AA0];
	if (n >= REG_AB0 && n < REG_AB0 + 8) return m_core->ab[n - REG_AB0];
	if (n >= REG_MA0 && n < REG_MA0 + 8) return m_core->ma[n - REG_MA0];
	if (n >= REG_MB0 && n < REG_MB0 + 8) return m_core->mb[n - REG_MB0];
	if (n >= REG_AR0 && n < REG_AR0 + 8) return m_core->ar[n - REG_AR0];
	if (n >= REG_PCS0 && n < REG_PCS0 + 4) return m_core->pcs[n - REG_PCS0];
	if (n >= REG_PR0 && n < REG_PR0 + 24) return m_core->pr[n - REG_PR0];
	switch (n)
	{
	case REG_PC:  return m_core->pc;
	case REG_MOD: return m_core->mod;
	case REG_EB:  return m_core->eb;
	case REG_EO:  return m_core->eo;
	case REG_SP:  return m_core->sp;
	case REG_PDR: return m_core->pdr;
	case REG_DDR: return m_core->ddr;
	case REG_RPC: return m_core->rpc;
	case REG_LPC: return m_core->lpc;
	case REG_PRP: return m_core->prp;
	case REG_PWP: return m_core->pwp;
	case REG_ST:  return m_core->st;
	case REG_PPC: return m_core->ppc;
	case REG_PCP: return m_core->pcp;
	default:      return 0;
	}
}

void CMB86235::SetReg(unsigned n, UINT32 v)
{
	if (n >= REG_AA0 && n < REG_AA0 + 8) { m_core->aa[n - REG_AA0] = v; return; }
	if (n >= REG_AB0 && n < REG_AB0 + 8) { m_core->ab[n - REG_AB0] = v; return; }
	if (n >= REG_MA0 && n < REG_MA0 + 8) { m_core->ma[n - REG_MA0] = v; return; }
	if (n >= REG_MB0 && n < REG_MB0 + 8) { m_core->mb[n - REG_MB0] = v; return; }
	if (n >= REG_AR0 && n < REG_AR0 + 8) { m_core->ar[n - REG_AR0] = v & 0x3fff; return; }
	if (n >= REG_PCS0 && n < REG_PCS0 + 4) { m_core->pcs[n - REG_PCS0] = v; return; }
	if (n >= REG_PR0 && n < REG_PR0 + 24) { m_core->pr[n - REG_PR0] = v; return; }
	switch (n)
	{
	case REG_PC:
		// next instruction at v (drops a pending delay slot or FIFO retry)
		m_core->pc = v;
		m_core->delay_slot = false;
		m_core->cur_fifo_state.has_stalled = false;
		break;
	case REG_MOD: m_core->mod = v; break;
	case REG_EB:  m_core->eb = v; break;
	case REG_EO:  m_core->eo = v; break;
	case REG_SP:  m_core->sp = v; break;
	case REG_PDR: m_core->pdr = v; break;
	case REG_DDR: m_core->ddr = v; break;
	case REG_RPC: m_core->rpc = v; break;
	case REG_LPC: m_core->lpc = v; break;
	case REG_PRP: if (v < 24) m_core->prp = v; break;
	case REG_PWP: if (v < 24) m_core->pwp = v; break;
	case REG_ST:  m_core->st = v; break;
	case REG_PPC: m_core->ppc = v; break;
	case REG_PCP: m_core->pcp = v & 3; break;
	default:      break;
	}
}


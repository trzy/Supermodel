inline void CMB86235::push_pc(uint32_t pcval)
{
	m_core->pcs[m_core->pcp++] = pcval;
	m_core->pcp &= 3;
//  if(m_core->pcp & ~3)
//      fatalerror("TGPx4: push_pc overflow PCP=%08x PC=%03x\n",m_core->pcp,m_core->ppc);
}

inline uint32_t CMB86235::pop_pc()
{
	m_core->pcp--;
	m_core->pcp &= 3;
//  if(m_core->pcp & ~3)
//      fatalerror("TGPx4: pop_pc underflow PCP=%08x PC=%03x\n",m_core->pcp,m_core->ppc);

	return m_core->pcs[m_core->pcp];
}

inline uint32_t CMB86235::do_control_dst(uint64_t op)
{
	uint32_t addr = 0;

	switch ((op >> 13) & 7)
	{
	case 0: // immediate
		addr = op & 0xfff;
		break;
	case 1: // register ARx
		addr = m_core->ar[(op >> 6) & 7];
		break;
	case 2:
		addr = BIT(op, 11) ? m_core->ab[(op >> 6) & 7] : m_core->aa[(op >> 6) & 7];
		break;
	case 3:
		addr = BIT(op, 11) ? m_core->mb[(op >> 6) & 7] : m_core->ma[(op >> 6) & 7];
		break;
	case 4:
		addr = read_abus(op & 0x3ff);
		break;
	case 5:
		addr = read_bbus(op & 0x3ff);
		break;
	case 6:
		addr = read_abus(m_core->ar[(op >> 6) & 7]);
		break;
	case 7:
		addr = read_bbus(m_core->ar[(op >> 6) & 7]);
		break;
	}

	if (BIT(op, 12))
	{
		m_core->icount--;
		return (m_core->pc + addr) & 0xfff;
	}
	else
		return addr & 0xfff;
}

inline void CMB86235::set_mod(uint16_t mod1, uint16_t mod2)
{
	m_core->mod &= ~mod1;
	m_core->mod |= mod2;
}

inline bool CMB86235::decode_branch_jump(uint8_t which)
{
	if (which < 19)
	{
		const uint32_t condition_table[19] = { MN, MZ, MV, MU, ZD, NR, IL, ZC, AN, AZ,
											   AV, AU, MD, AD, 0, 0, F0, F1, F2 };

		return (m_core->st & condition_table[which]) != 0;
	}
	else switch (which)
	{
	case 20: // IFF
		return m_fifoin->is_full();
	case 21: // IFE
		return m_fifoin->is_empty();
	case 22: // OFF
		return m_fifoout->is_full();
	case 23: // OFE
		return m_fifoout->is_empty();
	case 24: // IF
		return false;   // bit 33 of input FIFO; not used by Model 2
	default:
		fatalerror("TGPx4: illegal decode_branch_jump mode %02x at pc=%03x\n", which, m_core->ppc);
	}


	return false;
}

void CMB86235::do_alu_control(uint64_t op)
{
	uint32_t cop = (op >> 22) & 0x1f;
	uint32_t ef1 = (op >> 16) & 0x3f;
	uint16_t ef2 = op & 0xffff;

	switch(cop)
	{
		case 0x00: // NOP
			break;
		case 0x01: // REP
			if(ef1 == 0x3f)
				m_core->rpc = m_core->ar[(ef2 >> 13) & 7];
			else
				m_core->rpc = ef2;

			FSET(RP); // set repeat flag
			break;
		case 0x02: // SETL
			if(ef1 == 0x3f)
				m_core->lpc = m_core->ar[(ef2 >> 13) & 7];
			else
				m_core->lpc = ef2;

			FSET(LP); // set repeat flag
			break;
		case 0x03: // CLRF
			if(ef1 & 1) // clear fifo in (CLRFI)
			{
				if(m_fifoin)
					m_fifoin->clear();
			}
			if(ef1 & 2) // clear fifo out (CLRFO)
			{
				if(m_fifoout)
					m_fifoout->clear();
			}
			break;
		case 0x04: // PUSH
			m_core->sp--;
			m_core->sp &= 0x3ff;
			m_datab.write_dword(m_core->sp, get_transfer_reg((ef2>>6) & 0x3f));
			break;
		case 0x05: // POP
			// wait until ALU operation(s) have finished before popping
			break;
		case 0x08: // SETM
			set_mod(0xffff, ef2);
			break;
		case 0x09: // SETMCBSA
			set_mod(0x7000, ef2);
			break;
		case 0x0a: // SETMCBSB
			set_mod(0x0e00, ef2);
			break;
		case 0x0b: // SETMRF
			set_mod(0x0080, ef2);
			break;
		case 0x0c: // SETMRDY
			set_mod(0x0010, ef2);
			break;
		case 0x0d: // SETMWAIT
			set_mod(0x0007, ef2);
			break;

		// control flow
		case 0x10: // DBcc
		{
			bool result = decode_branch_jump(ef1);
			if(result == true)
			{
				m_core->delay_slot = true;
				m_core->delay_pc = do_control_dst(op);
			}
			m_core->icount--;
			break;
		}
		case 0x11: // DBNcc
		{
			bool result = decode_branch_jump(ef1);
			if(result == false)
			{
				m_core->delay_slot = true;
				m_core->delay_pc = do_control_dst(op);
			}
			m_core->icount--;
			break;
		}
		case 0x12: // DJMP
		{
			m_core->delay_slot = true;
			m_core->delay_pc = do_control_dst(op);
			m_core->icount--;
			break;
		}
		case 0x13: // DBLP
		{
			if(m_core->st & LP)
			{
				m_core->delay_slot = true;
				// relative addressing only
				m_core->delay_pc = m_core->pc + (op & 0xfff);
				m_core->delay_pc&= 0xfff;
			}

			--m_core->lpc;
			if(m_core->lpc == 1)
				FCLR(LP);
			break;
		}
		case 0x14: // DBBC
		{
			bool result = m_core->ar[(op >> 13) & 7] & (1 << ((op >> 16) & 0xf));
			if (result == false)
			{
				m_core->delay_slot = true;
				m_core->delay_pc = m_core->pc + (op & 0xfff);
				m_core->delay_pc &= 0xfff;
			}
			m_core->icount -= 2;
			break;
		}
		case 0x15: // DBBS
		{
			bool result = m_core->ar[(op >> 13) & 7] & (1 << ((op >> 16) & 0xf));
			if (result == true)
			{
				m_core->delay_slot = true;
				m_core->delay_pc = m_core->pc + (op & 0xfff);
				m_core->delay_pc &= 0xfff;
			}
			m_core->icount -= 2;
			break;
		}
		case 0x18: // DCcc
		{
			bool result = decode_branch_jump(ef1);
			if(result == true)
			{
				m_core->delay_slot = true;
				m_core->delay_pc = do_control_dst(op);
				push_pc(m_core->pc+1);
			}
			m_core->icount--;
			break;
		}
		case 0x19: // DCNcc
		{
			bool result = decode_branch_jump(ef1);
			if(result == false)
			{
				m_core->delay_slot = true;
				m_core->delay_pc = do_control_dst(op);
				push_pc(m_core->pc+1);
			}
			m_core->icount--;
			break;
		}
		case 0x1a: // DCALL
			m_core->delay_slot = true;
			m_core->delay_pc = do_control_dst(op);
			push_pc(m_core->pc+1);
			break;
		case 0x1b: // DRET
			m_core->delay_slot = true;
			m_core->delay_pc = pop_pc();
			break;
		default:
			fatalerror("TGPx4: illegal control op %02x at pc=%03x\n", cop, m_core->ppc);
	}

	// do alu
	if (BIT(op, 63))
		do_alu1(op);
	else
		do_alu2(op);

	// now we can safely pop if needed
	if (cop == 0x05)
	{
		set_transfer_reg((ef2 >> 6) & 0x3f, m_datab.read_dword(m_core->sp));
		m_core->sp++;
		m_core->sp &= 0x3ff;
	}
}


/******************************************************************************
 MAME's mb86235.cpp (interpreter loop)
******************************************************************************/

/* Execute cycles */
void CMB86235::execute_run()
{
	uint64_t opcode;
	while(m_core->icount > 0)
	{
		uint32_t curpc;

		curpc = check_previous_op_stall() ? m_core->cur_fifo_state.pc : m_core->pc;

		if (m_trace)
			m_trace(curpc);   // debugger_instruction_hook
		opcode = m_program[curpc & (PROGRAM_WORDS - 1)];   // Supermodel: was m_pcache.read_qword(curpc)

		m_core->ppc = curpc;

		if(m_core->delay_slot == true)
		{
			m_core->pc = m_core->delay_pc;
			m_core->delay_slot = false;
		}
		else
			handle_single_step_execution();

		m_core->cur_fifo_state.has_stalled = false;

		m_executing = true;   // Supermodel: Stall() allowed
		execute_op(opcode);
		m_executing = false;

		m_core->icount--;

		// Supermodel: a FIFO stall ends the slice (MAME's FIFO sync timer
		// aborts the timeslice); the instruction is retried on the next Run()
		// by check_previous_op_stall(). SetHalt(true) and EndSlice()
		// from inside the instruction end the slice too.
		if (m_core->cur_fifo_state.has_stalled || m_endSlice)
			break;
	}

}



namespace
{
  // MAME's emu_fatalerror: thrown, caught by CMB86235::Run(), which stops the core
  struct MB86235FatalError : public std::runtime_error
  {
    explicit MB86235FatalError(const char *msg) : std::runtime_error(msg) {}
  };

  MB86235FatalError emu_fatalerror(const char *fmt, ...)
  {
    char buf[512];
    va_list vl;
    va_start(vl, fmt);
    vsnprintf(buf, sizeof(buf), fmt, vl);
    va_end(vl);
    return MB86235FatalError(buf);
  }

  template <typename T, typename U> constexpr T BIT(T x, U n) { return (x >> n) & T(1); }

  // corefloat.h
  inline float u2f(uint32_t v) { float f; std::memcpy(&f, &v, sizeof(f)); return f; }
  inline uint32_t f2u(float f) { uint32_t v; std::memcpy(&v, &f, sizeof(v)); return v; }

  // Supermodel: uint32_t(f) is undefined for f outside [0, 2^32) and differs
  // between compilers; this is what GCC/Clang x86-64 (MAME's usual build)
  // produce: a 64-bit truncating conversion (cvttss2si), low 32 bits
  inline uint32_t float_to_u32(float f)
  {
    if (!(f > -9223372036854775808.0f && f < 9223372036854775808.0f))
      return 0;   // NaN or out of range: 0x8000000000000000
    return uint32_t(int64_t(f));
  }

  // Supermodel: int(f) likewise (cvttss2si: 0x80000000 when out of range)
  inline int float_to_int(float f)
  {
    if (!(f >= -2147483648.0f && f < 2147483648.0f))
      return int(0x80000000u);
    return int(f);
  }
}


// transfer type 3
void CMB86235::do_trans1_3(uint64_t op)
{
	uint8_t dr   = (op >> 19) & 0x7f;
	uint32_t imm = (op >> 27) & 0xffffffff;

	if(dr & 0x40)
	{
		bool isbbus = (dr & 0x20) == 0x20;
		uint32_t addr = decode_ea(op & 0xf,dr & 7,(op >> 4) & 7, (op >> 7) & 0xfff,isbbus);
		if (isbbus)
			write_bbus(addr, imm);
		else
			write_abus(addr, imm);
	}
	else // direct imm reg
		set_transfer_reg(dr,imm);
}


/*
 * bin2c.c
 *
 * Build tool for the libretro core: converts a file into a C array so that
 * it can be compiled into the core (used for the built-in copy of
 * Config/Games.xml). Portable C11, built with the host compiler like the
 * Musashi generator, so no external tools (xxd etc.) are needed.
 *
 * Usage: bin2c <input> <output> <symbol>
 *
 * Emits:  static const unsigned char <symbol>[] = { ..., 0 };
 *         static const unsigned long <symbol>_size = <file size>;
 */

#include <stdio.h>

int main(int argc, char **argv)
{
  FILE *in, *out;
  unsigned long size = 0;
  int c;

  if (argc != 4)
  {
    fprintf(stderr, "Usage: %s <input> <output> <symbol>\n", argv[0]);
    return 1;
  }

  in = fopen(argv[1], "rb");
  if (!in)
  {
    fprintf(stderr, "bin2c: unable to open '%s'\n", argv[1]);
    return 1;
  }
  out = fopen(argv[2], "w");
  if (!out)
  {
    fprintf(stderr, "bin2c: unable to create '%s'\n", argv[2]);
    fclose(in);
    return 1;
  }

  fprintf(out, "/* Generated by bin2c from %s -- do not edit */\n", argv[1]);
  fprintf(out, "static const unsigned char %s[] =\n{\n", argv[3]);
  while ((c = fgetc(in)) != EOF)
  {
    fprintf(out, "%u,", (unsigned) c);
    if ((++size % 32) == 0)
      fputc('\n', out);
  }
  /* Terminating zero so the data can also be used as a C string */
  fprintf(out, "0\n};\n");
  fprintf(out, "static const unsigned long %s_size = %luUL;\n", argv[3], size);

  fclose(in);
  fclose(out);
  return 0;
}

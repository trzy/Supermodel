void CVideo::Init(const Memory &memory)
{
  m_bufferram = memory.bufferRAM;
  m_palram = memory.paletteRAM;
  m_colorxlat = memory.colorXlat;
  m_lumaram = memory.lumaRAM;
  m_textureram0 = memory.textureRAM0;
  m_textureram1 = memory.textureRAM1;
  m_gamma_table = memory.gamma;

  // raster_init
  m_raster = std::make_unique<raster_state>();
  m_raster->texture_rom = memory.textureROM;
  m_raster->texture_rom_mask = memory.textureROMWords - 1;

  // geo_init
  m_geo = std::make_unique<geo_state>();
  m_geo->raster = m_raster.get();
  m_geo->polygon_rom = memory.polygonROM;
  m_geo->polygon_rom_mask = memory.polygonROMWords - 1;

  Reset();
}

void CVideo::Reset()
{
  m_geo_read_start_address = 0;
  m_geo_mesh = m_geoMeshGame;
  m_crtc_xoffset = m_crtc_yoffset = 0;
  m_xoffs = 90;
  m_yoffs = -8;
  render_frame_start();
  m_render_done = false;
  std::fill(m_destmap.begin(), m_destmap.end(), 0u);
  std::fill(m_fillmap.begin(), m_fillmap.end(), (uint8_t) 0);
}

// What MAME saves (the polygon list isn't: a loaded state shows the 3D from the next frame)
void CVideo::SaveState(CBlockFile *SaveState)
{
  SaveState->NewBlock("Model 2 Video", __FILE__);
  const raster_state &r = *m_raster;
  SaveState->Write(r.command_buffer);
  SaveState->Write(r.command_index);
  SaveState->Write(r.cur_command);
  SaveState->Write(r.master_z_clip);
  SaveState->Write(r.polygon_z);
  SaveState->Write(r.z_adjust);
  SaveState->Write(r.reverse);
  SaveState->Write(r.viewport);
  SaveState->Write(r.center);
  SaveState->Write(r.center_sel);
  SaveState->Write(r.texture_ram);
  SaveState->Write(r.log_ram);
  SaveState->Write(r.cur_window);
  SaveState->Write(r.clip_plane);
  const geo_state &g = *m_geo;
  SaveState->Write(g.mode);
  SaveState->Write(g.matrix);
  SaveState->Write(g.mesh_begin);
  SaveState->Write(g.mesh_current);
  SaveState->Write(g.mesh_texture_start);
  SaveState->Write(g.mesh_texture_begin);
  SaveState->Write(g.mesh_texture_next);
  SaveState->Write(g.mesh_texture_end);
  SaveState->Write(g.mesh_mode);
  SaveState->Write(g.mesh_uv);
  SaveState->Write(g.focus);
  SaveState->Write(g.light);
  SaveState->Write(g.lod);
  SaveState->Write(g.coef_table);
  SaveState->Write(g.texture_parameters);
  SaveState->Write(g.polygon_ram0);
  SaveState->Write(g.polygon_ram1);
  SaveState->Write(m_geo_mesh);
  SaveState->Write(m_crtc_xoffset);
  SaveState->Write(m_crtc_yoffset);
  SaveState->Write(m_xoffs);
  SaveState->Write(m_yoffs);

  // The last frame (the polygons themselves aren't kept): shown again after a
  // load until the geometrizer's next frame, so a paused load shows it
  SaveState->Write(m_render_done);
  SaveState->Write(m_gpuQuads);
  uint32_t n = (uint32_t) m_gpuVertices.size();
  SaveState->Write(n);
  if (n)
    SaveState->Write(m_gpuVertices.data(), n * (uint32_t) sizeof(GPUVertex));
  SaveState->Write(m_destmap.data(), (uint32_t) (m_destmap.size() * sizeof(m_destmap[0])));
  SaveState->Write(m_fillmap.data(), (uint32_t) m_fillmap.size());
  if (m_geoTopSkater)
  {
    SaveState->NewBlock("Model 2 Video Top Skater", __FILE__);
    SaveState->Write(m_geo->matrix2);
  }
}

void CVideo::LoadState(CBlockFile *SaveState)
{
  if (Result::OKAY != SaveState->FindBlock("Model 2 Video"))
  {
    ErrorLog("Unable to load Model 2 video state. Save state file is corrupt.");
    return;
  }
  raster_state &r = *m_raster;
  SaveState->Read(r.command_buffer);
  SaveState->Read(r.command_index);
  SaveState->Read(r.cur_command);
  SaveState->Read(r.master_z_clip);
  SaveState->Read(r.polygon_z);
  SaveState->Read(r.z_adjust);
  SaveState->Read(r.reverse);
  SaveState->Read(r.viewport);
  SaveState->Read(r.center);
  SaveState->Read(r.center_sel);
  SaveState->Read(r.texture_ram);
  SaveState->Read(r.log_ram);
  SaveState->Read(r.cur_window);
  SaveState->Read(r.clip_plane);
  geo_state &g = *m_geo;
  SaveState->Read(g.mode);
  SaveState->Read(g.matrix);
  SaveState->Read(g.mesh_begin);
  SaveState->Read(g.mesh_current);
  SaveState->Read(g.mesh_texture_start);
  SaveState->Read(g.mesh_texture_begin);
  SaveState->Read(g.mesh_texture_next);
  SaveState->Read(g.mesh_texture_end);
  SaveState->Read(g.mesh_mode);
  SaveState->Read(g.mesh_uv);
  SaveState->Read(g.focus);
  SaveState->Read(g.light);
  SaveState->Read(g.lod);
  SaveState->Read(g.coef_table);
  SaveState->Read(g.texture_parameters);
  SaveState->Read(g.polygon_ram0);
  SaveState->Read(g.polygon_ram1);
  SaveState->Read(m_geo_mesh);
  SaveState->Read(m_crtc_xoffset);
  SaveState->Read(m_crtc_yoffset);
  SaveState->Read(m_xoffs);
  SaveState->Read(m_yoffs);
  render_frame_start();

  // The last frame
  bool renderDone = false, quads = false;
  uint32_t n = 0;
  SaveState->Read(renderDone);
  SaveState->Read(quads);
  SaveState->Read(n);
  m_gpuVertices.resize(std::min<uint32_t>(n, 0x100000));
  if (n)
    SaveState->Read(m_gpuVertices.data(), (uint32_t) (m_gpuVertices.size() * sizeof(GPUVertex)));
  SaveState->Read(m_destmap.data(), (uint32_t) (m_destmap.size() * sizeof(m_destmap[0])));
  SaveState->Read(m_fillmap.data(), (uint32_t) m_fillmap.size());
  if (quads != m_gpuQuads)
  {
    // built as the other primitive (the state was saved with the other
    // QuadRendering setting): converted, the same polygons
    std::vector<GPUVertex> converted;
    const std::vector<GPUVertex> &v = m_gpuVertices;
    if (quads)
    {
      // quads to triangles: a padded triangle (vertex 3 = vertex 2) is one
      for (size_t i = 0; i + 4 <= v.size(); i += 4)
      {
        converted.insert(converted.end(), { v[i], v[i + 1], v[i + 2] });
        if (memcmp(&v[i + 3], &v[i + 2], sizeof(GPUVertex)) != 0)
          converted.insert(converted.end(), { v[i], v[i + 2], v[i + 3] });
      }
    }
    else
    {
      // triangles to quads: each a triangle, padded
      for (size_t i = 0; i + 3 <= v.size(); i += 3)
        converted.insert(converted.end(), { v[i], v[i + 1], v[i + 2], v[i + 2] });
    }
    m_gpuVertices = std::move(converted);
  }
  m_render_done = renderDone;
  ComputeClipPlanes();   // for this session's wide screen setting (the same planes without it)
  if (m_geoTopSkater && Result::OKAY == SaveState->FindBlock("Model 2 Video Top Skater"))
    SaveState->Read(m_geo->matrix2);
}


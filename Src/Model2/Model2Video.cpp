/* Command 00: NOP */
CVideo::WPtr CVideo::geo_nop(geo_state &geo, u32 opcode, WPtr input)
{
	raster_state *raster = geo.raster;

	/* push the opcode to the 3d rasterizer */
	model2_3d_push(raster, opcode >> 23);

	return input;
}

/* Command 01: Object Data */
CVideo::WPtr CVideo::geo_object_data(geo_state &geo, u32 opcode, WPtr input)
{
	raster_state *raster = geo.raster;
	u32  tpa = *input++;     /* Texture Point Address */
	u32  tha = *input++;     /* Texture Header Address */
	u32  oba = *input++;     /* Object Address */
	u32  obc = *input++;     /* Object Count */

	WPtr obp;                /* Object Pointer */

	// Supermodel: Top Skater's command 11 objects repeat the rasterizer
	// command in their low byte, with the center select (bits 6-7) that the
	// high one lacks: its speed meter is drawn around center 1, at the bottom
	// left of its window (opcode 08805151)
	u32 command = opcode >> 23;
	if (m_geoTopSkater && (command & 0x1f) == 0x11)
		command = (command & ~0xc0u) | (opcode & 0xc0);

	/* push the initial set of data to the 3d rasterizer */
	model2_3d_push(raster, command);
	model2_3d_push(raster, tpa);
	model2_3d_push(raster, tha);

	/* select where we're reading polygon information from */
	if (oba & 0x01000000)
	{
		/* Fast polygon RAM */
		obp = WPtr(geo.polygon_ram1, 0x7fff, oba & 0x7fff);
	}
	else if (oba & 0x00800000)
	{
		/* Polygon ROM */
		obp = WPtr(geo.polygon_rom, geo.polygon_rom_mask, oba & geo.polygon_rom_mask);
	}
	else
	{
		/* Slow Polygon RAM */
		obp = WPtr(geo.polygon_ram0, 0x7fff, oba & 0x7fff);
	}

	// if count == 0 then rolls over to max size
	// Virtual On & Gunblade NY
	if (obc == 0)
		obc = 0xfffff;

	// Supermodel: Top Skater's command 11 objects have compact link records
	// (no reserved normal and quad gap words)
	const bool compact = m_geoTopSkater && ((opcode >> 23) & 0x1f) == 0x11;

	switch (geo.mode & 3)
	{
		/* Normals present, No Specular */
		case 0: geo_parse_np_ns(geo, obp, obc); break;

		/* Normals present, Specular */
		case 1: geo_parse_np_s(geo, obp, obc); break;

		/* No Normals present, No Specular */
		case 2: geo_parse_nn_ns(geo, obp, obc, compact); break;

		/* No Normals present, Specular */
		case 3: geo_parse_nn_s(geo, obp, obc, compact); break;
	}

	/* move by 4 parameters */
	return input;
}

/* Command 02: Direct Data */
CVideo::WPtr CVideo::geo_direct_data(geo_state &geo, u32 opcode, WPtr input)
{
	raster_state *raster = geo.raster;
	u32  tpa = *input++;     /* Texture Point Address */
	u32  tha = *input++;     /* Texture Header Address */

	/* push the initial set of data to the 3d rasterizer */
	model2_3d_push(raster, (opcode >> 23) - 1);
	model2_3d_push(raster, tpa);
	model2_3d_push(raster, tha);

	/* push the initial points */
	model2_3d_push(raster, (*input++) >> 8); /* x */
	model2_3d_push(raster, (*input++) >> 8); /* y */
	model2_3d_push(raster, (*input++) >> 8); /* z */

	model2_3d_push(raster, (*input++) >> 8); /* x */
	model2_3d_push(raster, (*input++) >> 8); /* y */
	model2_3d_push(raster, (*input++) >> 8); /* z */

	/* read in the attributes */
	u32  attr;
	while (((attr = *input++) & 3) != 0)
	{
		/* push attributes */
		model2_3d_push(raster, attr & 0x00ffffff);

		/* push luma */
		model2_3d_push(raster, (*input++) >> 8);

		/* push distance */
		model2_3d_push(raster, (*input++) >> 8);

		/* push the next point */
		model2_3d_push(raster, (*input++) >> 8); /* x */
		model2_3d_push(raster, (*input++) >> 8); /* y */
		model2_3d_push(raster, (*input++) >> 8); /* z */

		/* if it's a quad, output another point */
		if (attr & 1)
		{
			model2_3d_push(raster, (*input++) >> 8); /* x */
			model2_3d_push(raster, (*input++) >> 8); /* y */
			model2_3d_push(raster, (*input++) >> 8); /* z */
		}
	}

	/* we're done */
	model2_3d_push(raster, 0);

	return input;
}

/* Command 03: Window Data */
CVideo::WPtr CVideo::geo_window_data(geo_state &geo, u32 opcode, WPtr input)
{
	raster_state *raster = geo.raster;

	/* start by pushing the opcode */
	model2_3d_push(raster, opcode >> 23);

	raster->cur_window++;

	/*
	    we're going to move 6 coordinates to the 3d rasterizer:
	    - starting coordinate
	    - completion coordinate
	    - vanishing point 0 (eye mode 0)
	    - vanishing point 1 (eye mode 1)
	    - vanishing point 2 (eye mode 2)
	    - vanishing point 3 (eye mode 3)
	*/

	for (u32 i = 0; i < 6; i++)
	{
		/* read in the coordinate */
		u32 y = *input++;

		/* convert to the 3d rasterizer format (00XXXYYY) */
		u32 x = (y & 0x0fff0000) >> 4 ;
		y &= 0xfff;

		/* push it */
		model2_3d_push(raster, x | y);
	}

	return input;
}

/* Command 04: Texture Data Write */
CVideo::WPtr CVideo::geo_texture_data(geo_state &geo, u32 opcode, WPtr input)
{
	raster_state *raster = geo.raster;

	/* start by pushing the opcode */
	model2_3d_push(raster, opcode >> 23);

	/* push the starting address/dsp id */
	model2_3d_push(raster, *input++);

	/* get the count */
	u32 count = ListCount(*input++);

	/* push the count */
	model2_3d_push(raster, count);

	/* loop and send the data */
	for (u32 i = 0; i < count; i++)
		model2_3d_push(raster, *input++);

	return input;
}

/* Command 05: Polygon Data */
CVideo::WPtr CVideo::geo_polygon_data(geo_state &geo, u32 opcode, WPtr input)
{
	u32  address, count, i;
	u32 *ram;

	/* read in the address */
	address = *input++;

	/* prepare the pointer */
	if (address & 0x01000000)
	{
		/* Fast polygon RAM */
		ram = geo.polygon_ram1;
	}
	else
	{
		/* Slow Polygon RAM */
		ram = geo.polygon_ram0;
	}

	/* read the count */
	count = ListCount(*input++);

	/* move the data */
	for (i = 0; i < count; i++)
		ram[(address + i) & 0x7fff] = *input++;   // Supermodel: wraps (MAME wrote past the end)

	return input;
}

/* Command 06: Texture Parameters */
CVideo::WPtr CVideo::geo_texture_parameters(geo_state &geo, u32 opcode, WPtr input)
{
	u32  index;

	/* read in the index */
	index = ((*input++) >> 2) & 0x1f;   // Supermodel: masked (MAME wrote past the 32 entries)

	/* read in the conut */
	u32 const count = ListCount(*input++);

	for (u32 i = 0; i < count; i++)
	{
		/* read in the texture parameters */
		u32 const param = *input++;

		geo.texture_parameters[index].diffuse = float(param & 0xff);
		geo.texture_parameters[index].ambient = float((param >> 8) & 0xff);
		geo.texture_parameters[index].specular_control = (param >> 24) & 0xff;
		geo.texture_parameters[index].specular_scale = float((param >> 16) & 0xff);

		/* read in the distance coefficient */
		geo.coef_table[index] = u2f(*input++);

		index = (index + 1) & 0x1f;
	}

	return input;
}


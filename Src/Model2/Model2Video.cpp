/* Command 0E: Geo Test */
CVideo::WPtr CVideo::geo_test(geo_state &geo, u32 opcode, WPtr input)
{
	u32      data;

	/* fifo test */
	data = 1;

	for (u32 i = 0; i < 32; i++)
	{
		if (*input++ != data)
		{
			/* TODO: Set Red LED on */
			DebugLog("SEGA GEO: FIFO Test failed\n");
		}

		data <<= 1;
	}

	/* get the number of checksums we have to run */
	u32 const blocks = *input++;

	for (u32 i = 0; i < blocks; i++)
	{
		/* read in the address */
		u32 address = (*input++) & 0x7fffff;

		/* read in the count */
		u32 const count = ListCount(*input++);

		/* read in the checksum */
		u32 const checksum = *input++;

		/* reset the checksum counters */
		u32 sum_even = 0;
		u32 sum_odd = 0;

		for (u32 j = 0; j < count; j++)
		{
			address &= geo.polygon_rom_mask;
			data = geo.polygon_rom[address++];

			sum_even += data >> 16;
			sum_odd += data & 0xffff;
		}

		sum_even += checksum >> 16;
		sum_even &= 0xffff;

		sum_odd += checksum & 0xffff;
		sum_odd &= 0xffff;

		if (sum_even != 0 || sum_odd != 0)
		{
			/* TODO: Set Green LED on */
			DebugLog("SEGA GEO: Polygon ROM Test failed\n");
		}
	}

	return input;
}

